/**
 * Write src/buildInfo.ts from package.json version + git HEAD (+dirty) + local timestamp.
 * Run before electron-vite / pack so Settings and CLI --version show the build being packed.
 */
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

function git(cmd) {
  try {
    return execSync(cmd, { cwd: root, encoding: 'utf8' }).trim()
  } catch {
    return ''
  }
}

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const version = String(pkg.version || '0.0.0')
const sha = git('git rev-parse --short HEAD') || 'unknown'
const dirty = git('git status --porcelain') !== ''
const now = new Date()
const pad = (n) => String(n).padStart(2, '0')
const timestamp = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(now.getHours())}:${pad(now.getMinutes())}`

const out = `// SPDX-License-Identifier: AGPL-3.0-only
// Copyright (C) 2026 Pomnia
/** Auto-generated by scripts/generate-build-info.mjs — do not edit by hand. */
export const BUILD_VERSION = ${JSON.stringify(version)}
export const BUILD_GIT_SHA = ${JSON.stringify(sha)}
export const BUILD_TIMESTAMP = ${JSON.stringify(timestamp)}
export const BUILD_DIRTY = ${dirty ? 'true' : 'false'}

/** \`0.1.44 · 4155ea9 · 2026-07-30 01:12\` (dirty → \`4155ea9+dirty\`). */
export function formatBuildIdentity(
  version = BUILD_VERSION,
  sha = BUILD_GIT_SHA,
  timestamp = BUILD_TIMESTAMP,
  dirty = BUILD_DIRTY,
): string {
  const ref = dirty ? \`\${sha}+dirty\` : sha
  return \`\${version} · \${ref} · \${timestamp}\`
}
`

const target = join(root, 'src', 'buildInfo.ts')
writeFileSync(target, out, 'utf8')
console.log(`buildInfo → ${formatPreview(version, sha, timestamp, dirty)}`)

function formatPreview(version, sha, timestamp, dirty) {
  const ref = dirty ? `${sha}+dirty` : sha
  return `${version} · ${ref} · ${timestamp}`
}
